# Create (or truncate) the log file and remember its path for Write-Log.
function Initialize-Log {
    param([string]$Path)
    $script:LogPath = $Path
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    "" | Set-Content -Path $Path -Encoding UTF8
}

# Write one log line to the console (colored by level) and append it to the log file.
function Write-Log {
    param(
        [string]$Message,
        [ValidateSet("INFO", "STEP", "OK", "WARN", "ERROR")]
        [string]$Level = "INFO"
    )

    $timestamp = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss")
    $fileLine = "[$timestamp] [$Level] $Message"

    $color = switch ($Level) {
        "STEP"  { "Cyan" }
        "OK"    { "Green" }
        "WARN"  { "Yellow" }
        "ERROR" { "Red" }
        default { "Gray" }
    }

    # The console stays clean and friendly: no timestamp / [LEVEL] noise - just a
    # small status glyph and the message. The LOG FILE always keeps the full
    # "[timestamp] [LEVEL] message" format for auditing.
    #   INFO  = detailed per-step chatter: file always; console only with -Verbose.
    #   STEP  = section / progress headers.
    #   OK/WARN/ERROR = outcomes, always shown.
    if ($Level -ne "INFO" -or $script:VerboseMode) {
        $glyph = switch ($Level) {
            "OK"    { "  " + [char]0x2713 + " " }   # check mark
            "WARN"  { "  ! " }
            "ERROR" { "  " + [char]0x00D7 + " " }    # x
            "INFO"  { "    " }                        # indented, verbose only
            default { "" }                            # STEP
        }
        Write-Host ($glyph + $Message) -ForegroundColor $color
    }

    if ($script:LogPath) {
        Add-Content -Path $script:LogPath -Value $fileLine -Encoding UTF8
    }
}

# ============================================================================
#  Console spinner - shows an animated "working..." line with the current
#  phase + elapsed seconds while a long 'az' call blocks the main thread.
#  It runs in a separate runspace (so it keeps animating while we wait) and
#  writes directly to the console. It is automatically DISABLED when output
#  is redirected (piped/captured) or when -Verbose is on (so detailed log
#  lines aren't interleaved with the spinner).
# ============================================================================
$script:SpinnerState    = $null
$script:SpinnerPS       = $null
$script:SpinnerRunspace = $null
$script:SpinnerHandle   = $null

function Test-SpinnerEnabled {
    if ($script:VerboseMode) { return $false }
    try { if ([Console]::IsOutputRedirected) { return $false } } catch { return $false }
    return $true
}

function Start-Spinner {
    param([string]$Status = "Working")
    if (-not (Test-SpinnerEnabled)) { $script:SpinnerState = $null; return }
    Stop-Spinner   # ensure no previous spinner is running
    $state = [hashtable]::Synchronized(@{ Stop = $false; Status = $Status; Start = [datetime]::UtcNow; Width = 78 })
    $sb = {
        param($s)
        $frames = @([char]0x2814,[char]0x2812,[char]0x2811,[char]0x2819,[char]0x2838,[char]0x2834,[char]0x2826,[char]0x2807)
        $i = 0
        while (-not $s.Stop) {
            $f = $frames[$i % $frames.Length]; $i++
            $el = [int]([datetime]::UtcNow - $s.Start).TotalSeconds
            $line = "    $f $($s.Status) (${el}s)"
            if ($line.Length -gt $s.Width) { $line = $line.Substring(0, $s.Width) }
            try { [Console]::Write("`r" + $line.PadRight($s.Width)) } catch { return }
            Start-Sleep -Milliseconds 120
        }
    }
    $script:SpinnerRunspace = [runspacefactory]::CreateRunspace()
    $script:SpinnerRunspace.Open()
    $script:SpinnerPS = [powershell]::Create()
    $script:SpinnerPS.Runspace = $script:SpinnerRunspace
    [void]$script:SpinnerPS.AddScript($sb).AddArgument($state)
    $script:SpinnerHandle = $script:SpinnerPS.BeginInvoke()
    $script:SpinnerState = $state
}

function Update-Spinner {
    param([string]$Status)
    if ($script:SpinnerState) { $script:SpinnerState.Status = $Status }
}

function Stop-Spinner {
    if ($script:SpinnerState) { $script:SpinnerState.Stop = $true }
    if ($script:SpinnerPS) {
        try { $script:SpinnerPS.EndInvoke($script:SpinnerHandle) } catch { }
        try { $script:SpinnerPS.Dispose() } catch { }
    }
    if ($script:SpinnerRunspace) {
        try { $script:SpinnerRunspace.Close() } catch { }
        try { $script:SpinnerRunspace.Dispose() } catch { }
    }
    if ($script:SpinnerState) {
        try { [Console]::Write("`r" + (' ' * $script:SpinnerState.Width) + "`r") } catch { }
    }
    $script:SpinnerState = $null; $script:SpinnerPS = $null; $script:SpinnerRunspace = $null; $script:SpinnerHandle = $null
}

