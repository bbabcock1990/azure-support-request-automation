# Prompt with a shown [default]; empty input returns the default.
function Read-HostDefault {
    param([string]$Prompt, [string]$Default)
    if ($Default) {
        $answer = Read-Host "$Prompt [$Default]"
        if ([string]::IsNullOrWhiteSpace($answer)) { return $Default }
        return $answer
    }
    return Read-Host $Prompt
}

# Prompt for a yes/no answer with a default; returns $true/$false.
function Read-YesNo {
    param([string]$Prompt, [bool]$Default = $false)
    $suffix = if ($Default) { "[Y/n]" } else { "[y/N]" }
    $answer = Read-Host "$Prompt $suffix"
    if ([string]::IsNullOrWhiteSpace($answer)) { return $Default }
    return $answer -match '^(y|yes)$'
}

# Interactive wizard: asks plain-language questions and writes the settings file.
function Invoke-SettingsWizard {
    param([pscustomobject]$Catalog, [string]$OutPath)

    Write-Log "Starting interactive setup wizard." "STEP"
    Write-Host ""
    Write-Host "=== Azure Support Request setup ===" -ForegroundColor Cyan
    Write-Host "Answer a few questions and this will build your settings file." -ForegroundColor Cyan
    Write-Host "Press Enter to accept the [default] shown in brackets." -ForegroundColor DarkGray
    Write-Host ""

    Write-Host "-- Your contact info (used on every ticket) --" -ForegroundColor Cyan
    $firstName = Read-HostDefault "First name" ""
    $lastName = Read-HostDefault "Last name" ""
    $email = Read-HostDefault "Contact email" ""
    $timeZone = Read-HostDefault "Preferred time zone" "Central Standard Time"

    Write-Host ""
    Write-Host "-- The deployment / environment --" -ForegroundColor Cyan
    $derivedCustomer = Get-CustomerFromEmail $email
    $customerPrompt = if ($derivedCustomer) { "Customer name (optional, blank = '$derivedCustomer' from your email)" } else { "Customer name (optional)" }
    $customer = Read-HostDefault $customerPrompt ""
    $deployment = Read-HostDefault "Deployment / project name" ""
    $name = Read-HostDefault "Short label for this environment" $(if ($deployment) { "$deployment" } else { "environment-1" })

    # This tool supports Azure Commercial (AzureCloud) only.
    $cloud = "AzureCloud"

    $subscriptionId = Read-HostDefault "Subscription ID (GUID)" ""
    while (-not (Test-IsGuid $subscriptionId)) {
        Write-Log "That does not look like a valid GUID." "WARN"
        $subscriptionId = Read-HostDefault "Subscription ID (GUID)" ""
    }

    $region = Read-HostDefault "Azure region (e.g. Central US, East US)" "Central US"
    $skusRaw = Read-HostDefault "VM SKUs, comma-separated (optional)" ""
    $skus = @()
    if ($skusRaw) { $skus = @($skusRaw.Split(",") | ForEach-Object { $_.Trim() } | Where-Object { $_ }) }

    $severityChoice = Read-HostDefault "Severity (1=critical, 2=moderate, 3=minimal)" "1"
    $severity = switch ($severityChoice) { "2" { "moderate" } "3" { "minimal" } default { "critical" } }

    $businessImpact = Read-HostDefault "Business impact / urgency note (optional)" ""
    $relatedSr = Read-HostDefault "Related existing support request ID (optional)" ""

    Write-Host ""
    Write-Host "-- Which support requests do you need? --" -ForegroundColor Cyan
    $needs = [ordered]@{}

    # Ask about every need in the catalog; the catalog's "fields" list drives which
    # follow-up questions (quotas, zones, notes) we ask for each enabled need.
    foreach ($needProp in $Catalog.needs.PSObject.Properties) {
        $needKey = $needProp.Name
        $label = $needProp.Value.label
        if (-not (Read-YesNo "Open an SR for: $label ($needKey)?" $false)) {
            $needs[$needKey] = [ordered]@{ enabled = $false }
            continue
        }

        $needObj = [ordered]@{ enabled = $true }
        $fields = @($needProp.Value.fields)
        if ($fields -contains "quotas") {
            $quotaList = @()
            do {
                $fam = Read-HostDefault "  VM family for the quota (e.g. standardDSv5Family)" "standardDSv5Family"
                $limRaw = Read-HostDefault "  New total vCPU / cores limit for $fam" "200"
                $lim = 0; [void][int]::TryParse($limRaw, [ref]$lim)
                $quotaList += [ordered]@{ vmFamily = $fam; newLimit = $lim }
            } while (Read-YesNo "  Add another VM family / SKU to this quota request?" $false)
            $needObj["quotas"] = $quotaList
        }
        if ($fields -contains "zones") {
            $zonesRaw = Read-HostDefault "  Which availability zones? (comma-separated)" "1,2,3"
            $zones = @($zonesRaw.Split(",") | ForEach-Object { $z = 0; [void][int]::TryParse($_.Trim(), [ref]$z); $z } | Where-Object { $_ -gt 0 })
            $needObj["zones"] = $zones
        }
        $needNotes = Read-HostDefault "  Notes for this request (optional)" ""
        $needObj["notes"] = $needNotes
        $needs[$needKey] = $needObj
    }

    $settings = [ordered]@{
        _comment = "Generated by the -Interactive wizard. Re-run with -Interactive to regenerate, or edit by hand."
        contact = [ordered]@{
            firstName = $firstName
            lastName = $lastName
            primaryEmailAddress = $email
            country = "USA"
            preferredContactMethod = "email"
            preferredSupportLanguage = "en-US"
            preferredTimeZone = $timeZone
        }
        defaults = [ordered]@{
            cloud = $cloud
            severity = $severity
            advancedDiagnosticConsent = "No"
        }
        environments = @(
            [ordered]@{
                name = $name
                enabled = $true
                cloud = $cloud
                subscriptionId = $subscriptionId
                region = $region
                customer = $customer
                deployment = $deployment
                vmSkus = $skus
                businessImpact = $businessImpact
                relatedSupportRequestId = $relatedSr
                sourceLinks = @()
                needs = $needs
            }
        )
    }

    ConvertTo-SettingsText -Settings $settings | Set-Content -Path $OutPath -Encoding UTF8
    Write-Log "Settings written to $OutPath" "OK"
    Write-Host ""

    return (ConvertFrom-SettingsText (Get-Content -Raw -Path $OutPath))
}

