# ---- Escalation-ready email document ---------------------------------------------
# Builds a detailed, paste-ready document a Microsoft CSAM / account team can use to
# open a UAT / raise an escalation. A brief list is printed to the console; the full
# document is saved to a .txt file next to the results JSON.
#
# The "Workload environment", "Needed by", "Customer scenario" and "Desired outcome"
# lines are DERIVED (never asked of the customer): workload comes from the Deployment
# text, needed-by is ASAP because the customer has already opened the ticket, and the
# scenario/outcome are composed from the need type + region + business impact. No ACR
# figures are ever emitted.
function Get-WorkloadEnvironment {
    param([string]$Deployment)
    $d = "$Deployment".ToLower()
    if ($d -match 'prod|production')            { return "Prod" }
    if ($d -match 'dev[\s/_-]*test|devtest')    { return "Dev/Test" }
    if ($d -match 'stag')                       { return "Staging" }
    if ($d -match '\bdev\b|develop')            { return "Dev" }
    if ($d -match 'test|\bqa\b|\buat\b')        { return "Test" }
    return "Prod"   # customer has opened a real support ticket - assume production intent
}

function Get-CapacityKind {
    param($R)
    if ("$($R.ticketType)" -ne "quota") { return "technical" }
    $s = ("$($R.need) $($R.title)").ToLower()
    if ($s -match 'zonal|availability zone') { return "zonal" }
    if ($s -match 'spot|low[\s-]*priority')  { return "spot" }
    if ($s -match 'gpu')                      { return "gpu" }
    return "compute"
}

function Get-DerivedNarrative {
    param($R, [string]$WorkloadEnv)
    $region = if ($R.region) { $R.region } else { "the requested region" }
    $dep    = if ($R.deployment -and ("$($R.deployment)".Trim() -ne "$WorkloadEnv")) { "$($R.deployment) ($WorkloadEnv)" } else { $WorkloadEnv }
    $impact = "$($R.businessImpact)".Trim()
    $kind   = Get-CapacityKind $R
    switch ($kind) {
        "zonal" {
            $scenario = "The customer needs Availability Zone access for zone-restricted VM families in $region so their $dep workload can deploy across the requested zones (per-zone breakdown listed below)."
            $outcome  = "Azure whitelists the requested VM families in the restricted Availability Zones so the customer can deploy zonally in $region without further delay."
        }
        "spot" {
            $scenario = "The customer needs additional Spot (low-priority) vCPU capacity in $region for their $dep workload (VM families and core counts listed below)."
            $outcome  = "Azure approves the requested Spot quota so the customer can run the required low-priority capacity in $region without further delay."
        }
        "gpu" {
            $scenario = "The customer needs additional GPU (vCPU) capacity in $region for their $dep workload (VM families and core counts listed below)."
            $outcome  = "Azure approves the requested GPU quota so the customer can deploy the required accelerated capacity in $region without further delay."
        }
        "compute" {
            $scenario = "The customer needs additional compute (vCPU) capacity in $region for their $dep workload (VM families and core counts listed below)."
            $outcome  = "Azure approves the requested quota / limit increase so the customer can deploy the required capacity in $region without further delay."
        }
        default {
            $svc = if ($R.serviceDisplayName) { "$($R.serviceDisplayName) - $($R.problemClassificationDisplayName)" } else { "the requested capability" }
            $scenario = "The customer needs $svc for their $dep workload in $region."
            $outcome  = "Azure actions the request so the capability is enabled for the customer in $region without further delay."
        }
    }
    if ($impact) { $scenario = "$scenario Business impact: $impact" }
    return [pscustomobject]@{ Scenario = $scenario; Outcome = $outcome }
}

