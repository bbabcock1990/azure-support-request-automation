<#
.SYNOPSIS
    Creates one or many Azure support requests (SRs) for a customer from a simple
    settings file, so repetitive asks (quota, spot, zonal access, allocation blocks)
    don't each require hand-filling the portal.

.DESCRIPTION
    Three-layer design:
      1. Settings file  (azure-support-settings.txt)  - the ONLY file a user edits.
                          A simple "Key: value" text file: contact info + one block per
                          environment listing the "needs" to open. Generated by -Interactive.
      2. Catalog file   (azure-support-catalog.json)  - edited rarely. Maps each
                          friendly "need" to the correct Azure service + problem
                          classification + title/summary templates, and marks whether
                          it is a 'technical' or 'quota' ticket.
      3. This engine    - expands (settings x catalog) into one normalized ticket per
                          enabled need, resolves the service/classification IDs live,
                          builds any quota payload, and submits via the az support CLI.

    Every run writes a timestamped, color-coded log to the console AND a .log file,
    plus a machine-readable results .json.

.PARAMETER SettingsFile
    Path to the per-customer settings file (the file the user edits / the wizard writes).
    Plain-text 'Key: value' format by default; a .json file is also accepted.
.PARAMETER CatalogFile
    Optional path to an external need->service/classification catalog JSON that
    OVERRIDES the generic Azure catalog built into this script. If the file is
    absent, the built-in catalog is used. (The built-in catalog holds no customer
    values - all targets/zones/SKUs come from the settings file.)
.PARAMETER SkipDeltaCheck
    Skip the live 'az vm list-usage' delta check. By default the engine compares each
    target quota you specified against the subscription's CURRENT limit and only
    requests the shortfall - dropping (and logging) any VM family already at/above
    target, and skipping the whole SR if every target is already met.
.PARAMETER SkipRestrictionCheck
    Skip the live zonal restriction check. By default, for zonalWhitelisting the engine
    queries 'az vm list-skus' and only opens a zone-access request for the SKU x zone
    combinations that are actually RESTRICTED for the subscription - matching what the
    portal shows. With this switch, every requested zone is submitted regardless.
.PARAMETER Verbose
    (Common parameter.) Show the full, detailed per-step log on the console (service /
    classification resolution, delta math, payloads, etc.). Without it you get a clean,
    friendly summary on the console; the full detail is ALWAYS written to the log file.
.PARAMETER OutputFile
    Where the run's results summary JSON is written (defaults to a timestamped file).
.PARAMETER LogFile
    Where the run's full log is written (defaults to a timestamped file).
.PARAMETER Interactive
    Launch the plain-language setup wizard to build the settings file, then run.
.PARAMETER TestMode
    Mark every SR as a test: prefixes the title, prepends an "ignore and close" banner
    to the description, and forces severity to 'minimal'. Use for safe smoke tests.
.PARAMETER WhatIf
    Resolve everything and show what WOULD be created, but do not submit.
.PARAMETER DiscoverOnly
    Like -WhatIf but labels results "ResolvedOnly" (used to verify service/classification lookups).
.PARAMETER ValidateSubscriptionAccess
    Also run 'az account set' per ticket so a lack of access fails fast and clearly.

.EXAMPLE
    .\Create-AzureSupportRequests.ps1 -Interactive
    Build a settings file by answering questions, then create the SRs.

.EXAMPLE
    .\Create-AzureSupportRequests.ps1 -TestMode
    Live smoke test: create real SRs that are clearly marked as tests.

.EXAMPLE
    .\Create-AzureSupportRequests.ps1 -WhatIf
    Preview only - resolve everything but submit nothing.
#>
[CmdletBinding()]
