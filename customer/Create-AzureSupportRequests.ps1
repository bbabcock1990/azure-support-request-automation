    $E.Add("Tickets:         $($createdList.Count) created, $($wouldList.Count) preview, $($failedList.Count) failed")
    if ($TestMode) { $E.Add("NOTE:            TEST tickets - Support can ignore and close. Do NOT escalate.") }
    $E.Add("")
    $E.Add("PURPOSE")
    $E.Add("-------")
    $E.Add("The Azure Support Requests below have been raised on the customer's")
    $E.Add("subscription. Please review and, where appropriate, open a UAT or raise an")
    $E.Add("escalation with the relevant capacity or product team to expedite. Every")
    $E.Add("detail needed to action each request is included below.")
    $E.Add("")
    $E.Add("SUMMARY")
    $E.Add("-------")
    $i = 0
    foreach ($row in $emailRows) { $i++; $E.Add(("{0}. [{1}] {2}  -  SR {3}" -f $i, $row.Status, $row.R.title, $row.SR)) }
    $E.Add("")

    $i = 0
    foreach ($row in $emailRows) {
        $i++
        $r = $row.R
        $typeLabel = switch ("$($r.ticketType)") {
            "quota"     { "Quota / limit increase" }
            "technical" { "Technical" }
            default     { if ($r.ticketType) { "$($r.ticketType)" } else { "" } }
        }
        $E.Add("----------------------------------------------------------------")
        $E.Add(("REQUEST {0} of {1}: {2}" -f $i, $emailRows.Count, $r.title))
        $E.Add("----------------------------------------------------------------")
        $E.Add("SR number:        $($row.SR)")
        $E.Add("Status:           $($row.Status)")
        if ($r.environment)    { $E.Add("Environment:      $($r.environment)") }
        if ($r.customer)       { $E.Add("Customer:         $($r.customer)") }
        if ($r.deployment)     { $E.Add("Deployment:       $($r.deployment)") }
        if ($r.subscriptionId) { $E.Add("Subscription:     $($r.subscriptionId)") }
        if ($r.region)         { $E.Add("Region:           $($r.region)") }
        $E.Add("Cloud:            AzureCloud (Azure Commercial)")
        if ($r.serviceDisplayName) { $E.Add("Category:         $($r.serviceDisplayName) / $($r.problemClassificationDisplayName)") }
        if ($typeLabel)        { $E.Add("Request type:     $typeLabel") }
        if ($r.severity)       { $E.Add("Severity:         $($r.severity)") }
        if ($r.businessImpact) { $E.Add("Business impact:  $($r.businessImpact)") }
        if ($r.notes)          { $E.Add("Note:             $($r.notes)") }

        # Derived (not customer-supplied): workload from Deployment, needed-by = ASAP
        # (ticket already open), scenario/outcome composed from the need + impact.
        $wlEnv = Get-WorkloadEnvironment $r.deployment
        $neededBy = if ("$($row.SR)" -match '^\d{16}$') {
            "As soon as possible - the customer has already opened Azure support request $($row.SR)."
        } else {
            "As soon as possible - the customer has opened (or is opening) the Azure support request."
        }
        $narr = Get-DerivedNarrative -R $r -WorkloadEnv $wlEnv
        $E.Add("Workload env:     $wlEnv  (derived from Deployment)")
        $E.Add("Needed by:        $neededBy")
        $E.Add("Customer scenario: $($narr.Scenario)")
        $E.Add("Desired outcome:  $($narr.Outcome)")

        if (@($r.requestDetails).Count -gt 0) {
            $E.Add("")
            $E.Add("Requested new limits:")
            foreach ($d in @($r.requestDetails)) { $E.Add("  - $d") }
        }
        if ($row.Status -eq "Failed" -and $r.error) {
            $E.Add("")
            $E.Add("Failure reason:   $($r.error)")
        }
        $E.Add("")
    }

    $E.Add("Where to view: Azure Portal > Help + support > All support requests (Status = All).")
    $E.Add("Generated by azure-support-srs on $nowStr.")

    Write-Host "  Escalation email (for CSAM / account team)" -ForegroundColor Cyan
    $emailFile = [System.IO.Path]::ChangeExtension($OutputFile, $null) + "email.txt"
    $E -join "`r`n" | Set-Content -Path $emailFile -Encoding UTF8
    Write-Host ("    Saved: {0}" -f $emailFile) -ForegroundColor DarkGray
    Write-Host ""
    Write-Log "Escalation-ready email saved to $emailFile" "INFO"
}

