# Ensure the Azure CLI 'support' extension is installed (one-time per run). This
# extension's 'tickets create' waits for completion and returns the real ticket
# number, unlike a raw async REST PUT which can report false success.
$script:SupportExtChecked = $false
function Confirm-SupportExtension {
    if ($script:SupportExtChecked) { return }
    $installed = & az extension list --query "[?name=='support'].name" -o tsv 2>$null
    if (-not $installed) {
        Write-Log "Installing Azure CLI 'support' extension (one-time)..." "INFO"
        Invoke-AzCliText @("extension", "add", "--name", "support", "--only-show-errors") | Out-Null
    }
    $script:SupportExtChecked = $true
}

# ============================================================================
#  Live quota delta check
#  Query the subscription's CURRENT per-family (and regional) vCPU limits, then
#  keep only the quota asks that are actually a shortfall vs. the target the user
#  specified. This is what stops us opening tickets for quota the customer
#  already has.
# ============================================================================

# Build a lookup of current vCPU LIMITs for a subscription+region from az vm list-usage.
# Each usage row is indexed several ways so a settings SKU matches regardless of how
# it's written: by machine name (e.g. 'standarddsv5family'), by the friendly localName
# minus its ' vCPUs' suffix, AND by a normalized key with all spaces/underscores
# removed. That last one lets 'standardNCASv3_T4Family' (payload name) match the
# usage row 'Standard NCASv3_T4 Family' (spaced) with no usageName hint required.
function Get-VmUsageMap {
    param([string]$RegionCode, [string]$SubscriptionId)

    $map = @{}
    try {
        $usage = Invoke-AzCliJson @("vm", "list-usage", "-l", $RegionCode, "--subscription", $SubscriptionId, "-o", "json")
    }
    catch {
        Write-Log "Could not read current usage (az vm list-usage) for $RegionCode : $($_.Exception.Message)" "WARN"
        return $null
    }
    foreach ($u in @($usage)) {
        $limit = 0; [void][int]::TryParse("$($u.limit)", [ref]$limit)
        $nameKey = "$($u.name.value)".ToLower()
        if ($nameKey) {
            $map[$nameKey] = $limit
            $map[($nameKey -replace '[^a-z0-9]', '')] = $limit   # normalized (no spaces/underscores)
        }
        $localKey = ("$($u.localName)" -replace '\s*vCPUs\s*$', '').Trim().ToLower()
        if ($localKey) {
            $map[$localKey] = $limit
            $map[($localKey -replace '[^a-z0-9]', '')] = $limit
        }
    }
    return $map
}

# ----------------------------------------------------------------------------
#  Zonal (Availability Zone) helpers - used only by the zonalWhitelisting need.
#  Together they let us reproduce EXACTLY what the portal's "Zone access" flow
#  submits: a payload per SKU x restricted-zone, tagged with both the LOGICAL zone
#  (Zone 1/2/3) and the subscription-specific PHYSICAL zone (Physical AZ0N).
# ----------------------------------------------------------------------------

# Return a map of logical zone ("1","2","3") -> physical zone display ("Physical AZ01").
# The logical->physical mapping is DIFFERENT per subscription, so we read it live from
# the ARM locations API (availabilityZoneMappings). Cached per subscription+region.
function Get-ZoneMapping {
    param([string]$RegionCode, [string]$SubscriptionId)

    $cacheKey = "$SubscriptionId|$RegionCode"
    if ($script:ZoneMapCache.ContainsKey($cacheKey)) { return $script:ZoneMapCache[$cacheKey] }

    $map = @{}
    try {
        $url = "https://management.azure.com/subscriptions/$SubscriptionId/locations?api-version=2022-12-01"
        $resp = Invoke-AzCliJson @("rest", "--method", "get", "--url", $url, "-o", "json")
        $loc = @($resp.value) | Where-Object { "$($_.name)".ToLower() -eq $RegionCode.ToLower() } | Select-Object -First 1
        foreach ($m in @($loc.availabilityZoneMappings)) {
            # physicalZone looks like "centralus-az1"; the portal payload wants "Physical AZ01".
            $num = 0
            if ("$($m.physicalZone)" -match 'az(\d+)$') { $num = [int]$Matches[1] }
            $physicalDisplay = "Physical AZ{0:D2}" -f $num
            $map["$($m.logicalZone)"] = $physicalDisplay
        }
    }
    catch {
        Write-Log "Could not read availability-zone mapping for $RegionCode : $($_.Exception.Message)" "WARN"
    }
    $script:ZoneMapCache[$cacheKey] = $map
    return $map
}

# Return a map of VM family -> array of LOGICAL zones ("1","2","3") in which at least
# one SKU of that family is RESTRICTED for this subscription (reasonCode
# NotAvailableForSubscription). This mirrors what the portal's zone-access picker shows:
# only restricted SKU x zone combinations need a ticket. Cached per subscription+region.
# Families are keyed by a NORMALIZED name (lowercased, all non-alphanumerics stripped)
# so the payload name 'standardNCASv3_T4Family' matches the API's spaced
# 'Standard NCASv3_T4 Family' - some families report a machine name, others a friendly
# spaced name, and an exact match would silently drop the spaced ones (e.g. GPU SKUs).
function Get-SkuZoneRestrictions {
    param([string]$RegionCode, [string]$SubscriptionId)

    $cacheKey = "$SubscriptionId|$RegionCode"
    if ($script:SkuRestrictionCache.ContainsKey($cacheKey)) { return $script:SkuRestrictionCache[$cacheKey] }

    $result = @{}
    try {
        # NOTE: --all is REQUIRED. Without it, az vm list-skus hides SKUs that are
        # restricted for the subscription - which are exactly the zone-restricted
        # SKUs we need to detect. Omitting --all makes the API return [] and the
        # engine wrongly concludes "already whitelisted / nothing to request".
        $skus = Invoke-AzCliJson @("vm", "list-skus", "--all", "--location", $RegionCode, "--resource-type", "virtualMachines", "--subscription", $SubscriptionId, "-o", "json")
        foreach ($sku in @($skus)) {
            # Normalize the family name so spaced/underscored/mixed-case variants all
            # collapse to one key (e.g. 'Standard NCASv3_T4 Family' -> 'standardncasv3t4family').
            $famKey = ("$($sku.family)".ToLower() -replace '[^a-z0-9]', '')
            if (-not $famKey) { continue }
            foreach ($r in @($sku.restrictions)) {
                if ("$($r.type)" -ne "Zone") { continue }
                if ("$($r.reasonCode)" -ne "NotAvailableForSubscription") { continue }
                foreach ($z in @($r.restrictionInfo.zones)) {
                    $zStr = "$z"
                    if (-not $result.ContainsKey($famKey)) { $result[$famKey] = New-Object System.Collections.Generic.List[string] }
                    if (-not $result[$famKey].Contains($zStr)) { $result[$famKey].Add($zStr) }
                }
            }
        }
    }
    catch {
        Write-Log "Could not read SKU zone restrictions for $RegionCode : $($_.Exception.Message)" "WARN"
        $script:SkuRestrictionCache[$cacheKey] = $null   # signal "unavailable" -> caller falls back to all zones
        return $null
    }
    $script:SkuRestrictionCache[$cacheKey] = $result
    return $result
}

# Given a ticket's requested SKUs and a usage map, return only the SKUs whose target
# exceeds the current limit (the real shortfall). Every decision is logged verbosely:
# families already at/above target are dropped with an "already met" note. Each kept
# SKU is annotated with .currentLimit / .delta for the description. If the usage map
# is unavailable, all SKUs are kept (fail safe - better to ask than silently skip).
function Select-QuotaShortfall {
    param([object[]]$Skus, [hashtable]$UsageMap, [string]$TicketId)

    if (-not $UsageMap) {
        Write-Log "[$TicketId] Delta check unavailable - requesting full target for all SKUs." "WARN"
        return @($Skus)
    }
    $kept = @()
    foreach ($s in @($Skus)) {
        $lookup = if ($s.usageName) { "$($s.usageName)".ToLower() } else { "$($s.vmFamily)".ToLower() }
        $lookupNorm = $lookup -replace '[^a-z0-9]', ''
        $famNorm = "$($s.vmFamily)".ToLower() -replace '[^a-z0-9]', ''
        $current = $null
        if     ($UsageMap.ContainsKey($lookup))                         { $current = [int]$UsageMap[$lookup] }
        elseif ($UsageMap.ContainsKey("$($s.vmFamily)".ToLower()))      { $current = [int]$UsageMap["$($s.vmFamily)".ToLower()] }
        elseif ($UsageMap.ContainsKey($lookupNorm))                     { $current = [int]$UsageMap[$lookupNorm] }
        elseif ($UsageMap.ContainsKey($famNorm))                        { $current = [int]$UsageMap[$famNorm] }

        if ($null -eq $current) {
            Write-Log "[$TicketId] $($s.vmFamily): current limit not found in usage - including to be safe (target $($s.newLimit))." "WARN"
            $kept += $s
            continue
        }
        if ([int]$s.newLimit -le $current) {
            Write-Log "[$TicketId] $($s.vmFamily): target $($s.newLimit) already met (current limit $current) - SKIPPING (no ticket needed)." "OK"
            continue
        }
        $delta = [int]$s.newLimit - $current
        Write-Log "[$TicketId] $($s.vmFamily): current limit $current < target $($s.newLimit) - shortfall of $delta vCPUs, requesting increase." "INFO"
        $s | Add-Member -NotePropertyName currentLimit -NotePropertyValue $current -Force
        $s | Add-Member -NotePropertyName delta -NotePropertyValue $delta -Force
        $kept += $s
    }
    return @($kept)
}

# Submit one normalized ticket: resolve service/classification, apply TestMode banner,
# build the quota payload (for quota tickets), and create the SR. Returns a result object.
function Submit-Ticket {
    param(
        [pscustomobject]$Ticket,
        [pscustomobject]$Config,
        [hashtable]$ContactDetails
    )

    $id = Get-RequiredString $Ticket "id" "ticket"
    # Cloud is always Azure Commercial (AzureCloud) - it is not configurable.
    $cloud = "AzureCloud"
    $subscriptionId = Get-RequiredString $Ticket "subscriptionId" "ticket '$id'"

    if (-not (Test-IsGuid $subscriptionId)) {
        throw "ticket '$id' has invalid subscriptionId '$subscriptionId'."
    }

    Write-Log "Selecting cloud '$cloud' for subscription $subscriptionId" "INFO"
    Update-Spinner "Selecting subscription"
    Set-AzCloudForTicket -Cloud $cloud -SubscriptionId $subscriptionId

    # --- Live quota delta check (quota tickets only) ---------------------------
    # Compare each requested SKU against the subscription's CURRENT limit and keep
    # only the shortfall. If everything is already at/above target, skip the SR.
    # Zone-access tickets are exempt: per-zone whitelisting isn't exposed by the
    # usage API, so we can't diff it and always submit those.
    $ticketTypeForDelta = if ($Ticket.ticketType) { $Ticket.ticketType } else { "technical" }
    $hasZones = (@($Ticket.quotaZones | Where-Object { "$_".Trim() -ne "" }).Count -gt 0)
    # Fail fast (clear message) if a quota need was listed but no target numbers were
    # given, so we don't misreport it later as "already met".
    if ($ticketTypeForDelta -eq "quota" -and @($Ticket.quotaSkus).Count -eq 0) {
        throw "quota need '$($Ticket.need)' has no VM families. Add a line like '$($Ticket.need): standardDSv5Family=2500' to environment '$($Ticket.environment)' in the settings file."
    }
    if ($ticketTypeForDelta -eq "quota" -and -not $hasZones -and -not $SkipDeltaCheck) {
        $regionCodeForUsage = ($Ticket.region -replace "\s", "")
        Write-Log "Checking current quota vs target for $($Ticket.region) ($subscriptionId)..." "INFO"
        Update-Spinner "Checking current quota vs target"
        $usageMap = Get-VmUsageMap -RegionCode $regionCodeForUsage -SubscriptionId $subscriptionId
        # Filter to the real shortfall. Guard against PowerShell collapsing an empty
        # result to $null (which @(...) would turn into a 1-element [null] array).
        $Ticket.quotaSkus = @(Select-QuotaShortfall -Skus $Ticket.quotaSkus -UsageMap $usageMap -TicketId $id | Where-Object { $_ })
        if (@($Ticket.quotaSkus).Count -eq 0) {
            Write-Log "[$id] All target quotas already met on this subscription - no ticket needed. Skipping." "OK"
            return [pscustomobject]@{
                id = $id
                environment = $Ticket.environment
                need = $Ticket.need
                status = "Skipped"
                title = $Ticket.title
                reason = "All target quotas already satisfied on subscription (delta check)."
            }
        }
    }
    elseif ($ticketTypeForDelta -eq "quota" -and $hasZones) {
        Write-Log "[$id] Zone-access request: skipping vCPU delta check; instead checking SKU zone restrictions (az vm list-skus) to request only restricted zones." "INFO"
    }

    $endpoint = Get-ResourceManagerEndpoint
    Write-Log "Resolving Azure service: '$($Ticket.serviceDisplayName)'" "INFO"
    Update-Spinner "Resolving Azure service"
    $service = Resolve-Service -Ticket $Ticket -Cloud $cloud
    Write-Log "  -> service id $($service.id)" "INFO"
    Write-Log "Resolving problem classification: '$($Ticket.problemClassificationDisplayName)'" "INFO"
    Update-Spinner "Resolving problem classification"
    $classification = Resolve-ProblemClassification -Ticket $Ticket -Service $service -Cloud $cloud
    Write-Log "  -> classification id $($classification.id)" "INFO"
    $ticketName = New-SupportTicketName -Id $id

    $ticketTitle = Get-RequiredString $Ticket "title" "ticket '$id'"
    $ticketDescription = New-Description -Ticket $Ticket
    $ticketSeverity = if ($Ticket.severity) { $Ticket.severity } else { "moderate" }

    if ($TestMode) {
        $ticketTitle = "$TestBannerTitle$ticketTitle"
        $ticketDescription = "$TestBannerDescription$ticketDescription"
        $ticketSeverity = "minimal"
        Write-Log "TEST MODE: marking this SR as a test (title '[TEST - PLEASE IGNORE AND CLOSE]' + test banner in description) and setting severity to minimal" "INFO"
    }

    $advancedConsent = if ($Config.defaults.advancedDiagnosticConsent) { $Config.defaults.advancedDiagnosticConsent } else { "No" }
    $ticketType = if ($Ticket.ticketType) { $Ticket.ticketType } else { "technical" }

    # Human-readable per-request breakdown (families/zones + limits), reused in the
    # escalation email so a CSAM/account team can see exactly what was asked for.
    $requestDetails = @()

    # For quota tickets, build the required quota-change payload up front so we can
    # fail fast (with a clear message) instead of Azure silently rejecting it async.
    $quotaArgs = @()
    if ($ticketType -eq "quota") {
        $skus = @($Ticket.quotaSkus)
        if ($skus.Count -eq 0) {
            throw "ticket '$id' is a quota request but has no VM families. Add a line like '$($Ticket.need): standardDSv5Family=2500' to this environment in the settings file."
        }
        # Region code = region name with spaces removed ("Central US" -> "CentralUS").
        $regionCode = ($Ticket.region -replace "\s", "")
        # Dedicated (standard compute) vs LowPriority (spot); set by the catalog per need.
        $changeType = if ($Ticket.quotaChangeType) { $Ticket.quotaChangeType } else { "Dedicated" }
        $qcVersion = if ($Ticket.quotaChangeVersion) { $Ticket.quotaChangeVersion } else { "1.0" }
        # quotaChangeRequests is a list of {region, payload}; we build one entry per SKU
        # (and, for zone access, per SKU x zone). $summaryParts is just for the log line.
        $entries = @()
        $summaryParts = @()
        $payloadRows = New-Object System.Collections.Generic.List[object]   # structured per-request rows for the Payload Details table
        $zones = @($Ticket.quotaZones | Where-Object { "$_".Trim() -ne "" })
        $isZonal = ($zones.Count -gt 0)

        if ($isZonal) {
            # ---- Zonal (Availability Zone) access request ------------------------
            # Reproduce the portal's "Zone access" submission EXACTLY: Type=Zonal,
            # DeploymentStack=ARM, and both the LOGICAL zone (Zone N) and the
            # subscription-specific PHYSICAL zone (Physical AZ0N). We also mirror the
            # portal picker's behavior of only listing SKU x zone combinations that are
            # actually RESTRICTED for this subscription (checked via az vm list-skus).
            $regionCodeLower = $regionCode.ToLower()
            $zonalRegion = $regionCode.ToUpper()       # portal stores region uppercase for zone access
            $zoneMap = Get-ZoneMapping -RegionCode $regionCodeLower -SubscriptionId $subscriptionId
            Update-Spinner "Checking SKU zone restrictions"
            $restrictions = if ($SkipRestrictionCheck) { $null } else { Get-SkuZoneRestrictions -RegionCode $regionCodeLower -SubscriptionId $subscriptionId }
            if ($SkipRestrictionCheck) {
                Write-Log "[$id] Restriction check OFF (-SkipRestrictionCheck): requesting every listed zone for every family." "WARN"
            } elseif ($null -eq $restrictions) {
                Write-Log "[$id] Restriction data unavailable - requesting every listed zone for every family (fail-safe)." "WARN"
            }
            foreach ($s in $skus) {
                if (-not $s.vmFamily) { throw "ticket '$id' has a quota entry with no 'vmFamily' (e.g. standardDSv5Family)." }
                if ($s.newLimit -le 0) { throw "ticket '$id' has an invalid 'newLimit' for VM family '$($s.vmFamily)' (must be a positive count)." }
                # Normalize the family the SAME way the restriction map is keyed, so
                # spaced API family names (e.g. 'Standard NCASv3_T4 Family') match the
                # payload name ('standardNCASv3_T4Family') instead of being dropped.
                $famKey = ("$($s.vmFamily)".ToLower() -replace '[^a-z0-9]', '')
                $famRestricted = if ($null -ne $restrictions -and $restrictions.ContainsKey($famKey)) { @($restrictions[$famKey]) } else { @() }
                foreach ($z in $zones) {
                    $zStr = "$z"
                    # When we have restriction data, only request zones the family is actually
                    # restricted in (matching the portal). Otherwise request every listed zone.
                    if ($null -ne $restrictions -and $famRestricted -notcontains $zStr) {
                        Write-Log "[$id] $($s.vmFamily) zone ${zStr}: not restricted for this subscription (already available) - skipping." "INFO"
                        continue
                    }
                    $logicalDisplay = "Zone $zStr"
                    $physicalDisplay = if ($zoneMap.ContainsKey($zStr)) { $zoneMap[$zStr] } else { "Physical AZ{0:D2}" -f ([int]$zStr) }
                    $payload = "{VMFamily:$($s.vmFamily),NewLimit:$($s.newLimit),DeploymentStack:ARM,Type:Zonal,AvailabilityZone:$physicalDisplay,LogicalAvailabilityZone:$logicalDisplay}"
                    $entries += "{region:'$zonalRegion',payload:'$payload'}"
                    $summaryParts += "$($s.vmFamily)@$logicalDisplay/$physicalDisplay=>$($s.newLimit)"
                    $payloadRows.Add([pscustomobject]@{ Family = $s.vmFamily; ZoneNum = $zStr; Zone = $logicalDisplay; Physical = $physicalDisplay; Limit = $s.newLimit; Type = "Zonal"; Region = $zonalRegion; Raw = $payload })
                }
            }
            if ($entries.Count -eq 0) {
                Write-Log "[$id] All requested SKUs are already available in the requested zone(s) on this subscription - no zone-access ticket needed. Skipping." "OK"
                return [pscustomobject]@{
                    id = $id
                    environment = $Ticket.environment
                    need = $Ticket.need
                    status = "Skipped"
                    title = $Ticket.title
                    reason = "All requested SKUs already available (not zone-restricted) in the requested zones."
                }
            }
            $quotaArgs = @(
                "--quota-change-version", $qcVersion,
                "--quota-change-requests", ("[" + ($entries -join ",") + "]")
            )
            Write-Log "Zone-access payload ($($entries.Count) request(s), Type=Zonal, v$qcVersion): region=$zonalRegion; $($summaryParts -join ', ')" "INFO"
        }
        else {
            # ---- Standard / spot / GPU quota increase ---------------------------
            foreach ($s in $skus) {
                if (-not $s.vmFamily) { throw "ticket '$id' has a quota entry with no 'vmFamily' (e.g. standardDSv5Family)." }
                if ($s.newLimit -le 0) { throw "ticket '$id' has an invalid 'newLimit' for VM family '$($s.vmFamily)' (must be a positive vCPU count)." }
                $payload = "{VMFamily:$($s.vmFamily),NewLimit:$($s.newLimit),Type:$changeType}"
                $entries += "{region:'$regionCode',payload:'$payload'}"
                $summaryParts += "$($s.vmFamily)=>$($s.newLimit)"
                $payloadRows.Add([pscustomobject]@{ Family = $s.vmFamily; ZoneNum = $null; Zone = $null; Physical = $null; Limit = $s.newLimit; Type = $changeType; Region = $regionCode; Raw = $payload })
            }
            $quotaArgs = @(
                "--quota-change-version", $qcVersion,
                "--quota-change-requests", ("[" + ($entries -join ",") + "]")
            )
            Write-Log "Quota payload ($($entries.Count) request(s), Type=$changeType, v$qcVersion): region=$regionCode; $($summaryParts -join ', ')" "INFO"
        }

        # Append a per-AZ breakdown to the ticket description so the zone -> physical-AZ
        # mapping AND the exact payload sent to Azure are visible in the portal (Issue
        # details), which otherwise only renders the summary and hides the structured
        # quota-change payload.
        #
        # NOTE: the portal renders the description in a PROPORTIONAL font, so a
        # space-padded ASCII grid does NOT line up. Instead we use a self-labeling
        # layout (every value carries its own "Zone/AZ = N vCPUs" label) that reads
        # correctly regardless of font. Zonal tickets are grouped by Availability Zone.
        if ($payloadRows.Count -gt 0) {
            $nl = [Environment]::NewLine
            $rawRequests = "[" + ($entries -join ",") + "]"

            if ($isZonal) {
                # Zone access: show ONLY which SKU families are requested in which
                # Availability Zone (logical + physical). No vCPU / new-limit numbers
                # and no raw quota payload, so the ask reads as pure zone whitelisting.
                $sectionLines = @("Zone access details - VM SKU families requested per Availability Zone:", "")
                $zoneNums = @($payloadRows | Select-Object -ExpandProperty ZoneNum -Unique | Sort-Object { [int]$_ })
                foreach ($zn in $zoneNums) {
                    $zoneRecs = @($payloadRows | Where-Object { $_.ZoneNum -eq $zn })
                    $phys = $zoneRecs[0].Physical
                    $sectionLines += "Zone ${zn} (${phys}):"
                    foreach ($rec in $zoneRecs) {
                        $sectionLines += ("    - {0}" -f $rec.Family)
                    }
                }
                $sectionLines += ""
                $sectionLines += "Request type: Availability Zone access (Zone access), Type=Zonal, DeploymentStack=ARM, Region=$zonalRegion."
                $sectionLines += "No quota / vCPU limit change is being requested."
                # Explain any requested family that isn't in the per-zone list above
                # because it's already available (not zone-restricted) - so the ask is
                # never silently inconsistent with the "requested families" header.
                $includedFamilies = @($payloadRows | Select-Object -ExpandProperty Family -Unique)
                $excludedFamilies = @($skus | ForEach-Object { $_.vmFamily } | Where-Object { $_ -and ($includedFamilies -notcontains $_) } | Select-Object -Unique)
                if ($excludedFamilies.Count -gt 0) {
                    $sectionLines += ""
                    $sectionLines += "Already available in the requested zone(s) - no zone access needed, not included above: $($excludedFamilies -join ', ')."
                }
            }
            else {
                $sectionLines = @("Payload Details - requested new limit (vCPUs):", "")
                foreach ($rec in $payloadRows) {
                    $sectionLines += ("    - {0} = {1} vCPUs  (Type: {2}, Region: {3})" -f $rec.Family, $rec.Limit, $rec.Type, $rec.Region)
                }
                $sectionLines += ""
                $sectionLines += "quotaChangeVersion: $qcVersion."
                $sectionLines += ""
                $sectionLines += "Raw quota-change-requests submitted to Azure:"
                $sectionLines += $rawRequests
            }

            $ticketDescription = "$ticketDescription$nl$nl" + ($sectionLines -join $nl)

            # Compact, paste-friendly breakdown for the escalation email.
            foreach ($rec in $payloadRows) {
                if ($rec.Type -eq "Zonal") {
                    $requestDetails += ("{0} ({1}): {2}" -f $rec.Zone, $rec.Physical, $rec.Family)
                } else {
                    $requestDetails += ("{0} = {1} vCPUs (Type: {2}, Region: {3})" -f $rec.Family, $rec.Limit, $rec.Type, $rec.Region)
                }
            }
        }
    }

    # -DiscoverOnly / -WhatIf: everything is resolved above; stop here without submitting.
    if ($DiscoverOnly -or $WhatIf) {
        Write-Log "Preview only ($(if ($DiscoverOnly){'DiscoverOnly'}else{'WhatIf'})) - not submitting '$ticketTitle'" "INFO"
        return [pscustomobject]@{
            id = $id
            environment = $Ticket.environment
            need = $Ticket.need
            status = if ($DiscoverOnly) { "ResolvedOnly" } else { "WouldCreate" }
            cloud = $cloud
            subscriptionId = $subscriptionId
            region = $Ticket.region
            severity = $ticketSeverity
            customer = $Ticket.customer
            deployment = $Ticket.deployment
            businessImpact = $Ticket.businessImpact
            notes = $Ticket.notes
            requestDetails = $requestDetails
            payload = @($payloadRows | Select-Object Family,ZoneNum,Zone,Physical,Limit,Type,Region)
            supportTicketName = $ticketName
            ticketType = $ticketType
            serviceDisplayName = $Ticket.serviceDisplayName
            problemClassificationDisplayName = $Ticket.problemClassificationDisplayName
            serviceId = $service.id
            problemClassificationId = $classification.id
            title = $ticketTitle
        }
    }

    Confirm-SupportExtension

    # Azure Support rejects angle brackets in the description (HTML-injection
    # protection), so replace them with safe equivalents. To preserve real line
    # breaks (the portal renders them) we write the description to a temp file and
    # let Azure CLI load it with its @file convention - this also sidesteps the
    # Windows az.cmd bug where embedded newlines in a command-line argument break
    # cmd.exe parsing.
    $ticketDescriptionClean = ($ticketDescription -replace "<", "(") -replace ">", ")"
    $descFile = [System.IO.Path]::Combine([System.IO.Path]::GetTempPath(), "srtool-desc-$([guid]::NewGuid().ToString('N')).txt")
    [System.IO.File]::WriteAllText($descFile, $ticketDescriptionClean, (New-Object System.Text.UTF8Encoding($false)))

    Write-Log "Submitting $ticketType support request '$ticketName' via az support ..." "INFO"
    Update-Spinner "Submitting to Azure"
    $createArgs = @(
        "support", "in-subscription", "tickets", "create",
        "--subscription", $subscriptionId,
        "--ticket-name", $ticketName,
        "--title", $ticketTitle,
        "--description", "@$descFile",
        "--severity", $ticketSeverity,
        "--problem-classification", $classification.id,
        "--contact-first-name", $ContactDetails.firstName,
        "--contact-last-name", $ContactDetails.lastName,
        "--contact-method", $ContactDetails.preferredContactMethod,
        "--contact-email", $ContactDetails.primaryEmailAddress,
        "--contact-country", $ContactDetails.country,
        "--contact-language", $ContactDetails.preferredSupportLanguage,
        "--contact-timezone", $ContactDetails.preferredTimeZone,
        "--advanced-diagnostic-consent", $advancedConsent,
        "--only-show-errors",
        "--output", "json"
    ) + $quotaArgs

    try {
        $response = Invoke-AzCliJson $createArgs
    }
    finally {
        Remove-Item $descFile -Force -ErrorAction SilentlyContinue
    }
    $ticketNumber = $response.supportTicketId
    if (-not $ticketNumber) { $ticketNumber = $response.name }
    Write-Log "Created SR $ticketNumber (status: $($response.status))" "INFO"

    return [pscustomobject]@{
        id = $id
        environment = $Ticket.environment
        need = $Ticket.need
        status = "Created"
        cloud = $cloud
        subscriptionId = $subscriptionId
        region = $Ticket.region
        severity = $ticketSeverity
        customer = $Ticket.customer
        deployment = $Ticket.deployment
        businessImpact = $Ticket.businessImpact
        notes = $Ticket.notes
        requestDetails = $requestDetails
        payload = @($payloadRows | Select-Object Family,ZoneNum,Zone,Physical,Limit,Type,Region)
        supportTicketName = $ticketName
        supportTicketId = $ticketNumber
        ticketType = $ticketType
        serviceDisplayName = $Ticket.serviceDisplayName
        problemClassificationDisplayName = $Ticket.problemClassificationDisplayName
        serviceId = $service.id
        problemClassificationId = $classification.id
        title = $ticketTitle
        portalUrl = "https://portal.azure.com/#blade/Microsoft_Azure_Support/HelpAndSupportBlade/managesupportrequest"
    }
}

