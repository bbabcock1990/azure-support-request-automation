# Run 'az ...' and return the parsed JSON object (throws with full output on failure).
function Invoke-AzCliJson {
    param([string[]]$Arguments)

    $previousErrorActionPreference = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $output = & az @Arguments 2>&1
    }
    finally {
        $ErrorActionPreference = $previousErrorActionPreference
    }

    if ($LASTEXITCODE -ne 0) {
        throw "az $($Arguments -join ' ') failed: $($output -join "`n")"
    }

    $text = ($output | Where-Object { "$_" -notmatch "^\s*WARNING:" }) -join "`n"
    if ([string]::IsNullOrWhiteSpace($text)) {
        return $null
    }

    return $text | ConvertFrom-Json
}

# Run 'az ...' and return raw text output (used for commands that don't emit JSON).
function Invoke-AzCliText {
    param([string[]]$Arguments)

    $previousErrorActionPreference = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $output = & az @Arguments 2>&1
    }
    finally {
        $ErrorActionPreference = $previousErrorActionPreference
    }

    if ($LASTEXITCODE -ne 0) {
        throw "az $($Arguments -join ' ') failed: $($output -join "`n")"
    }

    return ($output | Where-Object { "$_" -notmatch "^\s*WARNING:" }) -join "`n"
}

