# ============================================================================
#  Service / classification resolution - turn the friendly display names in the
#  catalog into the real Microsoft.Support resource IDs the API requires.
# ============================================================================

# Ensure the CLI is pointed at Azure Commercial (AzureCloud) and, optionally, the
# right subscription. Remembers the caller's original cloud once so the main block
# can restore it. (Only AzureCloud is supported; this guards against a CLI that was
# left set to another cloud.)
function Set-AzCloudForTicket {
    param(
        [string]$Cloud,
        [string]$SubscriptionId
    )

    if (-not $script:OriginalCloud) {
        $script:OriginalCloud = (Invoke-AzCliJson @("cloud", "show", "--output", "json")).name
    }

    $currentCloud = (Invoke-AzCliJson @("cloud", "show", "--output", "json")).name
    if ($currentCloud -ne $Cloud) {
        Invoke-AzCliText @("cloud", "set", "--name", $Cloud) | Out-Null
    }

    if ($ValidateSubscriptionAccess) {
        Invoke-AzCliText @("account", "set", "--subscription", $SubscriptionId) | Out-Null
    }
}

# The ARM endpoint for the currently-active cloud (AzureCloud = management.azure.com).
function Get-ResourceManagerEndpoint {
    $cloud = Invoke-AzCliJson @("cloud", "show", "--output", "json")
    return $cloud.endpoints.resourceManager.TrimEnd("/")
}

# List all Microsoft.Support services for the cloud (cached - the list is large and static).
function Get-SupportServices {
    param([string]$Cloud)

    if ($ServiceCache.ContainsKey($Cloud)) {
        return $ServiceCache[$Cloud]
    }

    $endpoint = Get-ResourceManagerEndpoint
    $uri = "$endpoint/providers/Microsoft.Support/services?api-version=$ApiVersion"
    $services = Invoke-AzCliJson @("rest", "--method", "get", "--url", $uri, "--output", "json")
    $ServiceCache[$Cloud] = @($services.value)
    return $ServiceCache[$Cloud]
}

# Find exactly one item whose displayName matches (exact, then contains, then keyword-AND).
# Throws a helpful error listing candidates if zero or many match - so a catalog typo is obvious.
function Find-SingleByDisplayName {
    param(
        [array]$Items,
        [string]$DisplayName,
        [string[]]$Keywords,
        [string]$Kind
    )

    $matches = @()

    if (-not [string]::IsNullOrWhiteSpace($DisplayName)) {
        $matches = @($Items | Where-Object { $_.properties.displayName -eq $DisplayName })
        if ($matches.Count -eq 0) {
            $matches = @($Items | Where-Object { $_.properties.displayName -like "*$DisplayName*" })
        }
    }
    elseif ($Keywords -and $Keywords.Count -gt 0) {
        $matches = @($Items | Where-Object {
            $display = $_.properties.displayName
            $matched = $true
            foreach ($keyword in $Keywords) {
                if ($display -notlike "*$keyword*") {
                    $matched = $false
                    break
                }
            }
            $matched
        })
    }

    if ($matches.Count -eq 1) {
        return $matches[0]
    }

    $candidateList = @($Items |
        Select-Object -First 20 |
        ForEach-Object { $_.properties.displayName }) -join "; "

    if ($matches.Count -gt 1) {
        $matchList = ($matches | ForEach-Object { $_.properties.displayName }) -join "; "
        throw "Multiple $Kind matches found: $matchList. Refine the catalog display name for this need."
    }

    throw "No $Kind match found. First candidates: $candidateList"
}

# Resolve the ticket's service display name to the Microsoft.Support service resource.
function Resolve-Service {
    param([pscustomobject]$Ticket, [string]$Cloud)

    $services = Get-SupportServices -Cloud $Cloud
    return Find-SingleByDisplayName `
        -Items $services `
        -DisplayName $Ticket.serviceDisplayName `
        -Kind "service"
}

# Resolve the ticket's problem-classification display name under its service (cached per service).
function Resolve-ProblemClassification {
    param(
        [pscustomobject]$Ticket,
        [pscustomobject]$Service,
        [string]$Cloud
    )

    $cacheKey = "$Cloud|$($Service.name)"
    if (-not $ClassificationCache.ContainsKey($cacheKey)) {
        $endpoint = Get-ResourceManagerEndpoint
        $uri = "$endpoint/providers/Microsoft.Support/services/$($Service.name)/problemClassifications?api-version=$ApiVersion"
        $classifications = Invoke-AzCliJson @("rest", "--method", "get", "--url", $uri, "--output", "json")
        $ClassificationCache[$cacheKey] = @($classifications.value)
    }

    return Find-SingleByDisplayName `
        -Items $ClassificationCache[$cacheKey] `
        -DisplayName $Ticket.problemClassificationDisplayName `
        -Kind "problem classification"
}

