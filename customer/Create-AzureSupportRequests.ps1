# Read a required field off a parsed object or throw a clear "missing field" error.
function Get-RequiredString {
    param(
        [pscustomobject]$Object,
        [string]$Name,
        [string]$Context
    )

    if (-not $Object.PSObject.Properties[$Name] -or [string]::IsNullOrWhiteSpace([string]$Object.$Name)) {
        throw "$Context is missing required field '$Name'."
    }

    return [string]$Object.$Name
}

# Build a unique, API-safe ticket-name (letters/digits/hyphens, <=40 chars + timestamp).
function New-SupportTicketName {
    param([string]$Id)

    $safe = ($Id -replace "[^A-Za-z0-9-]", "-").Trim("-")
    if ($safe.Length -gt 40) {
        $safe = $safe.Substring(0, 40).Trim("-")
    }

    return "$safe-$(Get-Date -Format 'yyyyMMddHHmmss')"
}

# Replace {token} placeholders in a title/summary template with real values.
function Expand-Template {
    param([string]$Template, [hashtable]$Tokens)

    if ([string]::IsNullOrWhiteSpace($Template)) {
        return $Template
    }

    $result = $Template
    foreach ($key in $Tokens.Keys) {
        $result = $result.Replace("{$key}", [string]$Tokens[$key])
    }
    return $result
}

# Resolve the contact block for tickets. Anything omitted in settings is auto-filled
# from the signed-in Azure AD user (name/email); the rest fall back to sensible defaults.
function New-ContactDetails {
    param([pscustomobject]$Config)

    $contact = $Config.contact
    if (-not $contact) {
        $contact = [pscustomobject]@{}
    }

    if (-not $contact.primaryEmailAddress -or -not $contact.firstName -or -not $contact.lastName) {
        try {
            $me = Invoke-AzCliJson @("ad", "signed-in-user", "show", "--output", "json")
            if (-not $contact.primaryEmailAddress) {
                $email = $me.mail
                if (-not $email) {
                    $email = $me.userPrincipalName
                }
                $contact | Add-Member -NotePropertyName primaryEmailAddress -NotePropertyValue $email -Force
            }
            if (-not $contact.firstName -or -not $contact.lastName) {
                $parts = ([string]$me.displayName).Split(" ", [System.StringSplitOptions]::RemoveEmptyEntries)
                if (-not $contact.firstName -and $parts.Count -ge 1) {
                    $contact | Add-Member -NotePropertyName firstName -NotePropertyValue $parts[0] -Force
                }
                if (-not $contact.lastName -and $parts.Count -ge 2) {
                    $contact | Add-Member -NotePropertyName lastName -NotePropertyValue $parts[-1] -Force
                }
            }
        }
        catch {
            throw "Contact details are incomplete and az ad signed-in-user show could not fill them. Add contact.firstName, contact.lastName, and contact.primaryEmailAddress to the settings file. $($_.Exception.Message)"
        }
    }

    return @{
        firstName = Get-RequiredString $contact "firstName" "contact"
        lastName = Get-RequiredString $contact "lastName" "contact"
        primaryEmailAddress = Get-RequiredString $contact "primaryEmailAddress" "contact"
        country = if ($contact.country) { $contact.country } else { "USA" }
        preferredContactMethod = if ($contact.preferredContactMethod) { $contact.preferredContactMethod } else { "email" }
        preferredSupportLanguage = if ($contact.preferredSupportLanguage) { $contact.preferredSupportLanguage } else { "en-US" }
        preferredTimeZone = if ($contact.preferredTimeZone) { $contact.preferredTimeZone } else { "Central Standard Time" }
    }
}

# Join an array (or scalar) into a readable comma-separated string, or $null if empty.
function ConvertTo-DisplayList {
    param($Value)
    if ($null -eq $Value) { return $null }
    return (@($Value) | ForEach-Object { [string]$_ }) -join ", "
}

# Default vCPU count used for a zonal-access family that lists no number and has no
