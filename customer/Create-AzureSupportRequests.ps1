$script:ZonalAccessDefaultCores = 100

# Look up a VM family's target vCPU limit from an environment's OTHER quota needs
# (computeQuota / gpuQuota / spotQuota). Used so zone-access families can be listed
# by SKU alone and inherit the number the customer already gave for that family.
function Get-FamilyLimitFromEnv {
    param([pscustomobject]$Environment, [string]$Family)
    if (-not $Environment.needs -or -not $Family) { return 0 }
    $normalize = { param($s) (([string]$s) -replace '[\s_]', '').ToLower() }
    $target = & $normalize $Family
    $needNames = @($Environment.needs.PSObject.Properties.Name)
    $preferred = @('computeQuota', 'gpuQuota', 'spotQuota')
    $ordered = @($preferred | Where-Object { $needNames -contains $_ }) +
               @($needNames | Where-Object { $preferred -notcontains $_ })
    foreach ($nn in $ordered) {
        if ($nn -eq 'zonalWhitelisting') { continue }
        $nd = $Environment.needs.$nn
        if (-not $nd -or -not $nd.quotas) { continue }
        foreach ($q in @($nd.quotas)) {
            if ((& $normalize ([string]$q.vmFamily)) -eq $target) {
                $lim = 0; [void][int]::TryParse([string]$q.newLimit, [ref]$lim)
                if ($lim -gt 0) { return $lim }
            }
        }
    }
    return 0
}

# Derive a customer / account name from a contact email's domain, e.g.
# jane@contoso.com -> "Contoso". Multi-part public suffixes (co.uk, com.au,
# co.jp, ...) are handled so we keep the registrable company label. Used when an
# Environment has no explicit Customer, so the customer running the tool only has
# to supply their own contact email.
function Get-CustomerFromEmail {
    param([string]$Email)
    if (-not $Email -or $Email -notmatch '@') { return $null }
    $domain = (($Email -split '@')[-1]).Trim().ToLower()
    if (-not $domain) { return $null }
    $labels = @($domain -split '\.' | Where-Object { $_ })
    if ($labels.Count -eq 0) { return $null }
    # Common second-level labels that precede a country-code TLD (co.uk, com.au, ne.jp...).
    $secondLevel = @('co','com','org','net','gov','edu','ac','gob','go','or','ne')
    if ($labels.Count -ge 3 -and $labels[-1].Length -le 3 -and ($secondLevel -contains $labels[-2])) {
        $core = $labels[-3]
    } elseif ($labels.Count -ge 2) {
        $core = $labels[-2]
    } else {
        $core = $labels[0]
    }
    if (-not $core) { return $null }
    return (Get-Culture).TextInfo.ToTitleCase($core)
}

# Turn one enabled need on one environment into a normalized ticket object the submitter understands.
function New-TicketFromNeed {
    param(
        [pscustomobject]$Config,
        [pscustomobject]$Environment,
        [string]$NeedKey,
        [pscustomobject]$NeedSettings,
        [pscustomobject]$CatalogEntry
    )

    # Customer precedence: explicit per-environment Customer > derived from the
    # contact email domain > the environment label. Derivation lets the customer
    # skip the Customer line entirely - their own email identifies their company.
    $customer = if ($Environment.customer) { $Environment.customer }
                elseif ($Config.contact.primaryEmailAddress) { Get-CustomerFromEmail $Config.contact.primaryEmailAddress }
                else { $Environment.name }
    if (-not $customer) { $customer = $Environment.name }
    $deployment = if ($Environment.deployment) { $Environment.deployment } else { $Environment.name }
    $region = [string]$Environment.region
    # Zones come only from the settings (the engine has no default zones).
    $zoneSource = if ($NeedSettings.zones) { @($NeedSettings.zones) } else { @() }
    $zones = ConvertTo-DisplayList $zoneSource
    # SKUs can be specified per-need, else inherited from the environment.
    $skus = ConvertTo-DisplayList $NeedSettings.vmSkus
    if (-not $skus) { $skus = ConvertTo-DisplayList $Environment.vmSkus }

    # Values available to the catalog's {token} title/summary templates.
    $tokens = @{
        customer   = $customer
        deployment = $deployment
        region     = $region
        zones      = $zones
        skus       = $skus
    }

    $title = Expand-Template $CatalogEntry.titleTemplate $tokens
    $summary = Expand-Template $CatalogEntry.summaryTemplate $tokens

    # Human-readable "Context:" bullet lines appended to every ticket description.
    $context = New-Object System.Collections.Generic.List[string]
    $context.Add("Customer: $customer")
    $context.Add("Deployment: $deployment")
    if ($region)  { $context.Add("Region: $region") }
    $context.Add("Subscription: $($Environment.subscriptionId)")
    if ($skus)    { $context.Add("VM families/SKUs: $skus") }
    if ($zones)   { $context.Add("Availability zones: $zones") }

    # Normalize quota SKUs so a single quota SR can cover multiple VM families,
    # each with its own new limit. Source precedence (no engine defaults):
    #   1. the 'quotas' array parsed from the settings need line, else
    #   2. the legacy single quotaVmFamily + requestedVCpus (back-compat).
    # 'usageName' is optional; it's only needed if a family's name in
    # 'az vm list-usage' differs from the payload name AND normalized matching
    # (which strips spaces/underscores) can't bridge it - normally you can omit it.
    $quotaSkus = @()
    $quotaSource = $null
    if ($NeedSettings.quotas) {
        $quotaSource = @($NeedSettings.quotas)
    }
    if ($quotaSource) {
        foreach ($q in $quotaSource) {
            $lim = 0; [void][int]::TryParse([string]$q.newLimit, [ref]$lim)
            $quotaSkus += [pscustomobject]@{
                vmFamily  = [string]$q.vmFamily
                newLimit  = $lim
                usageName = if ($q.usageName) { [string]$q.usageName } else { $null }
            }
        }
    } elseif ($NeedSettings.quotaVmFamily) {
        $lim = 0; [void][int]::TryParse([string]$NeedSettings.requestedVCpus, [ref]$lim)
        $quotaSkus += [pscustomobject]@{ vmFamily = [string]$NeedSettings.quotaVmFamily; newLimit = $lim; usageName = $null }
    }

    # Zone-access whitelisting is about SKU x zone access, not a quota increase, so
    # the customer may list families with no number. The portal payload still carries
    # a NewLimit per SKU x zone, so for any family missing a limit we inherit it from
    # the SAME environment's quota needs (computeQuota/gpuQuota/spotQuota) for that
    # family; if none is found we fall back to a documented default and warn.
    if ($NeedKey -eq 'zonalWhitelisting') {
        foreach ($qs in $quotaSkus) {
            if ([int]$qs.newLimit -le 0) {
                $inherited = Get-FamilyLimitFromEnv -Environment $Environment -Family $qs.vmFamily
                if ($inherited -gt 0) {
                    $qs.newLimit = $inherited
                    Write-Log "[$($Environment.name) :: $NeedKey] '$($qs.vmFamily)' has no zonal limit - inheriting $inherited vCPUs from this environment's quota needs." "INFO"
                } else {
                    $qs.newLimit = $script:ZonalAccessDefaultCores
                    Write-Log "[$($Environment.name) :: $NeedKey] '$($qs.vmFamily)' has no zonal limit and no matching quota need - defaulting to $($script:ZonalAccessDefaultCores) vCPUs. Add a number (family=limit) or a matching quota need to override." "WARN"
                }
            }
        }
    }

    if ($NeedKey -eq 'zonalWhitelisting') {
        # Zone access is about SKU x zone whitelisting, not a quota increase - so we
        # deliberately do NOT surface any vCPU / new-limit numbers in the human ask.
        $zonalFamilies = @($quotaSkus | ForEach-Object { $_.vmFamily } | Where-Object { $_ })
        if ($zonalFamilies.Count -gt 0) { $context.Add("VM families requested for zone access: $($zonalFamilies -join ', ')") }
    } else {
        foreach ($qs in $quotaSkus) { $context.Add("Quota: $($qs.vmFamily) new limit $($qs.newLimit) vCPUs") }
    }
    if ($Environment.businessImpact)  { $context.Add("Business impact: $($Environment.businessImpact)") }
    if ($Environment.relatedSupportRequestId) { $context.Add("Related existing support request: $($Environment.relatedSupportRequestId)") }
    if ($NeedSettings.notes) { $context.Add("Notes: $($NeedSettings.notes)") }

    $sourceLinks = @()
    if ($Environment.sourceLinks) { $sourceLinks = @($Environment.sourceLinks) }

    # Severity precedence: per-need > per-environment > defaults > "moderate".
    $severity = if ($NeedSettings.severity) { $NeedSettings.severity }
                elseif ($Environment.severity) { $Environment.severity }
                elseif ($Config.defaults.severity) { $Config.defaults.severity }
                else { "moderate" }

    # Cloud is always Azure Commercial (AzureCloud) - it is not configurable.
    $cloud = "AzureCloud"

    # The normalized ticket the submitter consumes. quota* fields are only used by quota tickets.
    return [pscustomobject]@{
        id = "$($Environment.name) :: $NeedKey"
        environment = $Environment.name
        customer = $customer
        deployment = $Environment.deployment
        businessImpact = $Environment.businessImpact
        need = $NeedKey
        cloud = $cloud
        subscriptionId = $Environment.subscriptionId
        region = $region
        severity = $severity
        ticketType = if ($CatalogEntry.ticketType) { $CatalogEntry.ticketType } else { "technical" }
        quotaChangeType = $CatalogEntry.quotaChangeType
        quotaChangeVersion = if ($CatalogEntry.quotaChangeVersion) { $CatalogEntry.quotaChangeVersion } else { "1.0" }
        quotaSkus = $quotaSkus
        quotaZones = @($zoneSource)
        serviceDisplayName = $CatalogEntry.serviceDisplayName
        problemClassificationDisplayName = $CatalogEntry.problemClassificationDisplayName
        title = $title
        description = $summary
        context = $context.ToArray()
        notes = $NeedSettings.notes
        requestedOutcome = $NeedSettings.requestedOutcome
        sourceLinks = $sourceLinks
        relatedSupportRequestId = $Environment.relatedSupportRequestId
    }
}

# Assemble the full multi-line ticket description: summary + Context + optional sections.
function New-Description {
    param([pscustomobject]$Ticket)

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add($Ticket.description)

    if ($Ticket.context) {
        $lines.Add("")
        $lines.Add("Context:")
        foreach ($item in @($Ticket.context)) {
            $lines.Add("- $item")
        }
    }

    # Quota request table (quota tickets). When the live delta check ran, each SKU
    # carries currentLimit/delta so Support sees exactly what to raise and by how much.
    # Zone-access (whitelisting) tickets are the exception: they intentionally show NO
    # vCPU numbers, because the ask is SKU x zone access, not a quota increase.
    $qskus = @($Ticket.quotaSkus)
    $isZonalDesc = (@($Ticket.quotaZones | Where-Object { "$_".Trim() -ne "" }).Count -gt 0)
    if ($qskus.Count -gt 0 -and $isZonalDesc) {
        $lines.Add("")
        $lines.Add("Zone access request details:")
        $lines.Add("Please enable / whitelist Availability Zone access for the following VM SKU families on this")
        $lines.Add("subscription. This is an access request only - do NOT change any vCPU / core quota limits.")
        foreach ($s in $qskus) {
            $lines.Add("- $($s.vmFamily)")
        }
        if ($Ticket.quotaZones) {
            $lines.Add("Availability zones: $((@($Ticket.quotaZones) | ForEach-Object { [string]$_ }) -join ', ')")
        }
    }
    elseif ($qskus.Count -gt 0) {
        $lines.Add("")
        $lines.Add("Quota request details:")
        foreach ($s in $qskus) {
            if ($null -ne $s.currentLimit) {
                $lines.Add("- $($s.vmFamily): current limit $($s.currentLimit) vCPUs, requesting $($s.newLimit) vCPUs (increase of $($s.delta)).")
            } else {
                $lines.Add("- $($s.vmFamily): requesting $($s.newLimit) vCPUs.")
            }
        }
    }

    if ($Ticket.requestedOutcome) {
        $lines.Add("")
        $lines.Add("Requested outcome:")
        $lines.Add($Ticket.requestedOutcome)
    }

    if ($Ticket.sourceLinks) {
        $lines.Add("")
        $lines.Add("Source/evidence links:")
        foreach ($link in @($Ticket.sourceLinks)) {
            $lines.Add("- $link")
        }
    }

    return $lines -join "`n"
}

# ============================================================================
#  Simple text settings format (.txt) - the human-friendly file users edit.
#  Instead of JSON braces/quotes, users write "Key: value" lines and list the
#  needs they want. This section parses that text into the same config object
#  the rest of the engine already consumes, and writes it back out (for the wizard).
# ============================================================================

# Deep-convert nested ordered hashtables/arrays into PSCustomObjects so downstream
# code (which enumerates $config...needs.PSObject.Properties) works unchanged.
function ConvertTo-PsObjectDeep {
    param($Value)
    if ($Value -is [System.Collections.IDictionary]) {
        $o = [ordered]@{}
        foreach ($k in $Value.Keys) { $o[$k] = ConvertTo-PsObjectDeep $Value[$k] }
        return [pscustomobject]$o
    }
    if ($Value -is [System.Array]) {
        return @($Value | ForEach-Object { ConvertTo-PsObjectDeep $_ })
    }
    return $Value
}

# Parse the simple "Key: value" settings text into a config object. Lines before the
# first "Environment:" set the contact/defaults; each "Environment:" starts a new
# environment block. Quota needs are declared as "<need>: family=limit, family=limit";
# "Zones:" sets zones for zonalWhitelisting; "Needs:" is a comma list of needs that
# take no numbers (e.g. haPostgres). The engine has no defaults - every number here.
function ConvertFrom-SettingsText {
    param([string]$Text)

    $contact  = [ordered]@{}
    $defaults = [ordered]@{}
    $envs     = New-Object System.Collections.Generic.List[object]
    $cur      = $null   # current environment (ordered hashtable) being filled

    foreach ($rawLine in ($Text -split "`r?`n")) {
        $line = $rawLine
        $trimmed = $line.Trim()
        if ($trimmed -eq "" -or $trimmed.StartsWith("#")) { continue }   # blank or comment
        $ci = $line.IndexOf(" #")                                        # strip inline comment
        if ($ci -ge 0) { $line = $line.Substring(0, $ci) }
        $idx = $line.IndexOf(":")
        if ($idx -lt 0) { continue }                                     # not a Key: value line
        $keyRaw = ($line.Substring(0, $idx).Trim() -replace '\s+', ' ')   # original case (for need names)
        $key = ($keyRaw.ToLower())
        $val = $line.Substring($idx + 1).Trim()

        # "Environment:" starts a new block.
        if ($key -eq "environment") {
            if ($cur) { $envs.Add($cur) }
            $cur = [ordered]@{
                name = $val; enabled = $true; cloud = $null; subscriptionId = $null; region = $null
                customer = $null; deployment = $null; vmSkus = @(); businessImpact = $null
                relatedSupportRequestId = ""; sourceLinks = @(); needs = ([ordered]@{})
            }
            continue
        }

        if (-not $cur) {
            # --- Global contact / defaults (before the first Environment:) ---
            switch ($key) {
                "contact name"  { $p = @($val -split '\s+'); if ($p.Count -ge 1) { $contact.firstName = ($p[0..([Math]::Max(0,$p.Count-2))] -join ' ') }; if ($p.Count -ge 2) { $contact.lastName = $p[-1] } }
                "contact email" { $contact.primaryEmailAddress = $val }
                "email"         { $contact.primaryEmailAddress = $val }
                "country"       { $contact.country = $val }
                "contact method"{ $contact.preferredContactMethod = $val }
                "method"        { $contact.preferredContactMethod = $val }
                "language"      { $contact.preferredSupportLanguage = $val }
                "support language" { $contact.preferredSupportLanguage = $val }
                "time zone"     { $contact.preferredTimeZone = $val }
                "timezone"      { $contact.preferredTimeZone = $val }
                "severity"      { $defaults.severity = $val }
                "consent"       { $defaults.advancedDiagnosticConsent = $val }
                "advanced diagnostic consent" { $defaults.advancedDiagnosticConsent = $val }
                default { }
            }
            continue
        }

        # --- Inside an environment block ---
        $needs = $cur.needs
        switch ($key) {
            "subscription"        { $cur.subscriptionId = $val }
            "subscription id"     { $cur.subscriptionId = $val }
            "region"              { $cur.region = $val }
            "customer"            { $cur.customer = $val }
            "deployment"          { $cur.deployment = $val }
            "business impact"     { $cur.businessImpact = $val }
            "vm skus"             { $cur.vmSkus = @($val -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) }
            "skus"                { $cur.vmSkus = @($val -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) }
            "related sr"                  { $cur.relatedSupportRequestId = $val }
            "related support request"     { $cur.relatedSupportRequestId = $val }
            "related support request id"  { $cur.relatedSupportRequestId = $val }
            "severity"            { $cur.severity = $val }
            "enabled"             { $cur.enabled = ($val -notmatch '^(false|no|0)$') }
            "needs" {
                foreach ($n in ($val -split ',')) {
                    $nk = $n.Trim()
                    if (-not $nk) { continue }
                    if ($needs.Contains($nk)) { $needs[$nk].enabled = $true } else { $needs[$nk] = [ordered]@{ enabled = $true } }
                }
            }
            "zones" {
                $z = @($val -split ',' | ForEach-Object { $i = 0; [void][int]::TryParse($_.Trim(), [ref]$i); $i } | Where-Object { $_ -gt 0 })
                if (-not $needs.Contains('zonalWhitelisting')) { $needs['zonalWhitelisting'] = [ordered]@{ enabled = $true } } else { $needs['zonalWhitelisting'].enabled = $true }
                $needs['zonalWhitelisting'].zones = $z
            }
            "zonalwhitelisting" {
                # Zone access is about SKU x zone access, not a quota increase, so the
                # per-family limit is OPTIONAL here. List families with or without a
                # number: "standardESv5Family" or "standardESv5Family=2500". When a
                # number is omitted the engine inherits it from the SAME environment's
                # quota needs (computeQuota/gpuQuota/spotQuota) for that family.
                if (-not $needs.Contains('zonalWhitelisting')) { $needs['zonalWhitelisting'] = [ordered]@{ enabled = $true } } else { $needs['zonalWhitelisting'].enabled = $true }
                $q = @()
                foreach ($pair in ($val -split ',')) {
                    $p = $pair.Trim(); if (-not $p) { continue }
                    if ($p -match '=') {
                        $f = $p.Split('=')[0].Trim()
                        $lim = 0; [void][int]::TryParse($p.Split('=')[1].Trim(), [ref]$lim)
                    } else { $f = $p; $lim = 0 }
                    if ($f) { $q += [ordered]@{ vmFamily = $f; newLimit = $lim } }
                }
                $needs['zonalWhitelisting'].quotas = $q
            }
            "override" {
                # Legacy/explicit form: "Override: <needKey> <family>=<limit>, ..."
                # (The simpler "<needKey>: <family>=<limit>, ..." form below is preferred.)
                $sp = $val.IndexOf(' ')
                if ($sp -gt 0) {
                    $nk = $val.Substring(0, $sp).Trim()
                    $rest = $val.Substring($sp + 1)
                    if (-not $needs.Contains($nk)) { $needs[$nk] = [ordered]@{ enabled = $true } } else { $needs[$nk].enabled = $true }
                    $q = @()
                    foreach ($pair in ($rest -split ',')) {
                        if ($pair -match '=') {
                            $f = $pair.Split('=')[0].Trim()
                            $lim = 0; [void][int]::TryParse($pair.Split('=')[1].Trim(), [ref]$lim)
                            if ($f) { $q += [ordered]@{ vmFamily = $f; newLimit = $lim } }
                        }
                    }
                    $needs[$nk].quotas = $q
                }
            }
            default {
                # Per-need notes: "<needName> notes: <free text>" attaches a Notes
                # line to that specific request's description, e.g.
                #   computeQuota notes: Remove restriction for creating new capacity ...
                if ($keyRaw -match '^\s*(.+?)\s+notes\s*$') {
                    $nkRaw = $matches[1].Trim()
                    $existing = @($needs.Keys | Where-Object { $_ -ieq $nkRaw }) | Select-Object -First 1
                    $nk = if ($existing) { $existing } else { $nkRaw }
                    if (-not $needs.Contains($nk)) { $needs[$nk] = [ordered]@{ enabled = $true } }
                    $needs[$nk].notes = $val
                    continue
                }
                # Any other "Key: value" line inside an environment is treated as a
                # NEED declaration (the key is the need name, original case preserved):
                #   Quota need  ->  value is a family=limit list, e.g.
                #      computeQuota: standardDSv5Family=2500, standardDDSv5Family=2000
                #   Technical need -> value is yes/true/on, e.g.  haPostgres: yes
                $nk = $keyRaw
                if ($val -match '=') {
                    if (-not $needs.Contains($nk)) { $needs[$nk] = [ordered]@{ enabled = $true } } else { $needs[$nk].enabled = $true }
                    $q = @()
                    foreach ($pair in ($val -split ',')) {
                        if ($pair -match '=') {
                            $f = $pair.Split('=')[0].Trim()
                            $lim = 0; [void][int]::TryParse($pair.Split('=')[1].Trim(), [ref]$lim)
                            if ($f) { $q += [ordered]@{ vmFamily = $f; newLimit = $lim } }
                        }
                    }
                    $needs[$nk].quotas = $q
                }
                elseif ($val -match '^(yes|true|enable|enabled|on|x)$') {
                    if (-not $needs.Contains($nk)) { $needs[$nk] = [ordered]@{ enabled = $true } } else { $needs[$nk].enabled = $true }
                }
            }
        }
    }
    if ($cur) { $envs.Add($cur) }

    # Fill sensible defaults so the rest of the engine always has what it expects.
    if (-not $defaults.Contains('severity')) { $defaults.severity = "moderate" }
    if (-not $defaults.Contains('advancedDiagnosticConsent')) { $defaults.advancedDiagnosticConsent = "No" }

    return [pscustomobject]@{
        contact      = ConvertTo-PsObjectDeep $contact
        defaults     = ConvertTo-PsObjectDeep $defaults
        environments = @($envs | ForEach-Object { ConvertTo-PsObjectDeep $_ })
    }
}

# Serialize a settings object (the ordered-hashtable shape the wizard builds) back
# into the simple text format, so -Interactive produces a file users can re-read/edit.
function ConvertTo-SettingsText {
    param($Settings)

    $L = New-Object System.Collections.Generic.List[string]
    $L.Add("# Azure Support Request - settings")
    $L.Add("# Lines starting with # are comments. Edit the value after each colon.")
    $L.Add("# Quota needs are written as '<need>: family=limit, family=limit'.")
    $L.Add("# Needs without numbers (e.g. haPostgres) are written as '<need>: yes'.")
    $L.Add("# See README.md for the full list of fields and needs.")
    $L.Add("")
    $c = $Settings.contact
    $L.Add("Contact name:    $(("$($c.firstName) $($c.lastName)").Trim())")
    $L.Add("Contact email:   $($c.primaryEmailAddress)")
    if ($c.country)                  { $L.Add("Country:         $($c.country)") }
    if ($c.preferredContactMethod)   { $L.Add("Contact method:  $($c.preferredContactMethod)") }
    if ($c.preferredSupportLanguage) { $L.Add("Language:        $($c.preferredSupportLanguage)") }
    if ($c.preferredTimeZone)        { $L.Add("Time zone:       $($c.preferredTimeZone)") }
    if ($Settings.defaults.severity) { $L.Add("Severity:        $($Settings.defaults.severity)") }

    foreach ($env in @($Settings.environments)) {
        $L.Add("")
        $L.Add("# ===== Environment block (repeat for more subscriptions/regions) =====")
        $L.Add("Environment:     $($env.name)")
        if ($env.enabled -eq $false)     { $L.Add("Enabled:         false") }
        $L.Add("Subscription:    $($env.subscriptionId)")
        $L.Add("Region:          $($env.region)")
        if ($env.customer)               { $L.Add("Customer:        $($env.customer)") }
        if ($env.deployment)             { $L.Add("Deployment:      $($env.deployment)") }
        if ($env.businessImpact)         { $L.Add("Business impact: $($env.businessImpact)") }
        if (@($env.vmSkus).Count -gt 0)  { $L.Add("VM SKUs:         $((@($env.vmSkus)) -join ', ')") }
        if ($env.relatedSupportRequestId){ $L.Add("Related SR:      $($env.relatedSupportRequestId)") }

        # Emit each enabled need. Quota needs get their own 'need: family=limit' line;
        # zonalWhitelisting also gets a 'Zones:' line; needs without numbers (technical)
        # are collected into a single 'Needs:' line.
        $plainNeeds = @()
        $zoneLine = $null
        foreach ($nk in $env.needs.Keys) {
            $need = $env.needs[$nk]
            if ($need.enabled -ne $true) { continue }
            if ($need.quotas -and @($need.quotas).Count -gt 0) {
                # For zonal, a family with no positive limit is written by SKU alone
                # (the limit is inherited from the environment's quota needs at run time).
                $pairs = @($need.quotas | ForEach-Object {
                    $lim = 0; [void][int]::TryParse([string]$_.newLimit, [ref]$lim)
                    if ($lim -gt 0) { "$($_.vmFamily)=$lim" } else { "$($_.vmFamily)" }
                }) -join ', '
                $L.Add("$($nk):".PadRight(17) + $pairs)
            } else {
                $plainNeeds += $nk
            }
            if ($nk -eq 'zonalWhitelisting' -and $need.zones -and @($need.zones).Count -gt 0) {
                $zoneLine = "Zones:".PadRight(17) + ((@($need.zones)) -join ', ')
            }
            if ($need.notes) { $L.Add("$nk notes:".PadRight(17) + $need.notes) }
        }
        if ($zoneLine) { $L.Add($zoneLine) }
        if ($plainNeeds.Count -gt 0) { $L.Add("Needs:".PadRight(17) + (($plainNeeds) -join ', ')) }
    }
    $L.Add("")
    return ($L -join "`r`n")
}

